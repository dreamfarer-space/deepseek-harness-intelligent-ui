#!/usr/bin/env node
/**
 * Generate client-src/catalog/map-land.ts: the offline world outline the `Map`
 * component draws when no tile provider is configured (or tiles fail).
 *
 * Source: world-atlas land-110m (Natural Earth 1:110m land, public domain;
 * world-atlas ISC). Coordinates are rounded to 0.1° and each ring is stored as
 * one string of base-36 deltas, so the outline costs ~30 KB in the bundle and
 * needs no network. Re-run after bumping world-atlas:
 *   node scripts/map/build-land.mjs
 */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const topo = JSON.parse(await readFile(resolve(root, 'node_modules/world-atlas/land-110m.json'), 'utf8'))
const { scale: [kx, ky], translate: [dx, dy] } = topo.transform

/** Delta-decoded, quantized arcs → [lon, lat] arrays. */
const arcs = topo.arcs.map(arc => {
  let x = 0, y = 0
  return arc.map(([qx, qy]) => { x += qx; y += qy; return [x * kx + dx, y * ky + dy] })
})
function ring(indexes) {
  const out = []
  for (const i of indexes) {
    const pts = i < 0 ? [...arcs[~i]].reverse() : arcs[i]
    // Consecutive arcs share their joining point.
    out.push(...(out.length ? pts.slice(1) : pts))
  }
  return out
}

const rings = []
for (const geometry of topo.objects.land.geometries) {
  const polygons = geometry.type === 'Polygon' ? [geometry.arcs] : geometry.arcs
  for (const polygon of polygons) for (const r of polygon) rings.push(ring(r))
}

/** Signed integer → base-36 token terminated by its sign character. */
const token = n => `${Math.abs(n).toString(36)}${n < 0 ? '-' : '+'}`
const encoded = []
let points = 0
for (const r of rings) {
  const q = []
  for (const [lon, lat] of r) {
    const p = [Math.round(lon * 10), Math.round(lat * 10)]
    const prev = q.at(-1)
    if (!prev || prev[0] !== p[0] || prev[1] !== p[1]) q.push(p)
  }
  if (q.length < 4) continue
  let px = 0, py = 0
  let s = ''
  for (const [x, y] of q) { s += token(x - px) + token(y - py); px = x; py = y }
  encoded.push(s)
  points += q.length
}

const out = `/* Generated by scripts/map/build-land.mjs from world-atlas land-110m
 * (Natural Earth 1:110m land, public domain). Do not edit. */

/** Rings of 0.1° base-36 deltas: "<|dx|><sign><|dy|><sign>…". */
const RINGS: readonly string[] = ${JSON.stringify(encoded)}

let decoded: [number, number][][] | undefined

/** World land rings as [lon, lat] degrees (${rings.length} rings, ${points} points). */
export function worldLand(): [number, number][][] {
  if (decoded) return decoded
  decoded = RINGS.map(s => {
    const out: [number, number][] = []
    const re = /([0-9a-z]+)([+-])([0-9a-z]+)([+-])/g
    let x = 0
    let y = 0
    for (const m of s.matchAll(re)) {
      x += parseInt(m[1]!, 36) * (m[2] === '-' ? -1 : 1)
      y += parseInt(m[3]!, 36) * (m[4] === '-' ? -1 : 1)
      out.push([x / 10, y / 10])
    }
    return out
  })
  return decoded
}
`
await writeFile(resolve(root, 'client-src/catalog/map-land.ts'), out)
console.log(`map-land.ts: ${encoded.length} rings, ${points} points, ${(out.length / 1024).toFixed(1)} KB`)
