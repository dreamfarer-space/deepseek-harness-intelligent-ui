#!/usr/bin/env node
/**
 * Bundle client-src/ into client/client.js — the CommonJS factory the DSH
 * Web shell loads via `window.__ModuleLoader__.load({ id, factory })`.
 *
 * Platform modules (React, Cordis, dsh-client-* shared table) stay external
 * and resolve through the factory's `require`; everything else is inlined.
 * Mirrors deepseek-harness packages/client/tsdown.client.ts (banner/footer)
 * and packages/client/web/src/platform.ts (externals).
 */
import { build } from 'esbuild'
import { readFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))

/** packages/client/web/src/platform.ts PLATFORM_MODULES */
const PLATFORM_MODULES = [
  'react', 'react/jsx-runtime', 'react-dom', 'react-dom/client', '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

/** `import SRC from 'idiomorph-source'` → the minified idiomorph global build as a string. */
const idiomorphSource = {
  name: 'idiomorph-source',
  setup(b) {
    b.onResolve({ filter: /^idiomorph-source$/ }, () => ({ path: resolve(root, 'node_modules/idiomorph/dist/idiomorph.min.js'), namespace: 'idiomorph-source' }))
    b.onLoad({ filter: /.*/, namespace: 'idiomorph-source' }, async args => ({
      contents: `export default ${JSON.stringify(await readFile(args.path, 'utf8'))}`,
      loader: 'js',
    }))
  },
}

const watch = process.argv.includes('--watch')
const options = {
  entryPoints: [resolve(root, 'client-src/index.ts')],
  outfile: resolve(root, 'client/client.js'),
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['es2020'],
  jsx: 'automatic',
  external: PLATFORM_MODULES,
  plugins: [idiomorphSource],
  minify: !process.argv.includes('--no-minify'),
  legalComments: 'eof',
  charset: 'utf8',
  banner: { js: `/* ${pkg.name} ${pkg.version} — generated by scripts/build-client.mjs; do not edit. */\nwindow.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory: (require) => {\nvar module = { exports: {} }; var exports = module.exports;` },
  footer: { js: 'return module.exports; } });' },
  logLevel: 'info',
}

if (watch) {
  const { context } = await import('esbuild')
  const c = await context(options)
  await c.watch()
} else {
  await build(options)
}
